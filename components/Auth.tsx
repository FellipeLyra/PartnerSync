import React, { useState } from 'react';
import { User, Company } from '../types';
import { auth, googleProvider } from '../firebaseConfig';
import * as firebaseAuth from 'firebase/auth';
import { storageService } from '../services/storageService';
import { Users, ArrowRight, Mail, Lock, User as UserIcon, Chrome, AlertTriangle, Copy, Phone, Eye, EyeOff } from 'lucide-react';
import { useToast } from '../contexts/ToastContext';

interface AuthProps {
  onLogin: (user: User) => void;
}

const Auth: React.FC<AuthProps> = ({ onLogin }) => {
  const [isRegistering, setIsRegistering] = useState(false);
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [confirmPassword, setConfirmPassword] = useState(''); // New: Confirm Password
  const [showPassword, setShowPassword] = useState(false); // New: Toggle Password
  const [showConfirmPassword, setShowConfirmPassword] = useState(false); // New: Toggle Confirm Password
  const [username, setUsername] = useState('');
  const [phone, setPhone] = useState('');
  const [inviteCode, setInviteCode] = useState('');
  const [isJoining, setIsJoining] = useState(false);
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(false);
  const { addToast } = useToast(); // New: Toast hook

  // Helper to sync Firebase Auth user to our DB User
  const handleAuthSuccess = async (firebaseUser: any, customUsername?: string) => {
    try {
      // 1. Check if user already exists in Firestore to preserve their Avatar/Data
      const existingUser = await storageService.getUser(firebaseUser.uid);

      if (existingUser) {
        // User exists: Use the data from database (preserves custom avatar)
        console.log("User found in DB, using existing data.");
        onLogin(existingUser);
      } else {
        // First time login
        let targetCompanyId = '';
        let userRole: 'ADMIN' | 'MEMBER' = 'ADMIN';

        if (isJoining && inviteCode) {
          // JOINING EXISTING COMPANY
          const company = await storageService.getCompanyByInviteCode(inviteCode);
          if (!company) {
            setError("Código de convite inválido ou não encontrado.");
            return; // Stop execution
          }
          targetCompanyId = company.id;
          userRole = 'MEMBER';
          console.log("Joining Company:", company.name);
        } else {
          // CREATING NEW COMPANY
          const newCompany: Company = {
            id: '', // Generated
            name: `${firebaseUser.displayName || firebaseUser.email}'s Company`,
            createdAt: Date.now(),
            ownerId: firebaseUser.uid,
            inviteCode: '', // Generated by service
            subscription: 'FREE' as const
          };

          targetCompanyId = await storageService.createCompany(newCompany);
          console.log("Created Company:", targetCompanyId);
        }

        // 2. Create User linked to Company
        const newUser: User = {
          id: firebaseUser.uid,
          username: customUsername || firebaseUser.displayName || firebaseUser.email?.split('@')[0] || 'User',
          email: firebaseUser.email || '',
          phone: phone, // Save phone number
          avatar: firebaseUser.photoURL || `https://ui-avatars.com/api/?name=${customUsername || firebaseUser.displayName || 'User'}`,
          companyId: targetCompanyId,
          role: userRole
        };

        await storageService.saveUser(newUser);
        onLogin(newUser);
      }
    } catch (err) {
      console.error("Error in handleAuthSuccess:", err);
      // Fallback cannot really work well without companyId, so we warn user or try best effort
      // For now, let's just alert
      setError("Erro ao criar perfil de usuário. Tente novamente.");
    }
  };

  const getErrorMessage = (err: any) => {
    console.error("Auth Error Detail:", err);
    if (err.code === 'auth/wrong-password') return "Senha incorreta.";
    if (err.code === 'auth/user-not-found') return "Usuário não encontrado.";
    if (err.code === 'auth/email-already-in-use') return "Email já cadastrado.";
    if (err.code === 'auth/weak-password') return "Senha muito fraca (mínimo 6 caracteres).";
    if (err.code === 'auth/popup-closed-by-user') return "Login cancelado.";
    if (err.code === 'auth/popup-blocked') return "Pop-up bloqueado. Permita pop-ups para este site.";

    if (err.code === 'auth/unauthorized-domain') {
      const currentDomain = window.location.hostname;
      return `DOMÍNIO BLOQUEADO: O endereço "${currentDomain}" não está autorizado.`;
    }

    if (err.code === 'permission-denied' || err.message?.includes('Missing or insufficient permissions')) {
      return "ERRO DE PERMISSÃO: Banco de dados bloqueado (Firestore Rules).";
    }

    return "Erro: " + (err.message || "Tente novamente.");
  };

  const handleGoogleLogin = async () => {
    if (!auth || !googleProvider) {
      setError("Firebase não configurado corretamente. Verifique firebaseConfig.ts");
      return;
    }
    setLoading(true);
    setError('');
    try {
      const result = await firebaseAuth.signInWithPopup(auth, googleProvider);
      await handleAuthSuccess(result.user);
    } catch (err: any) {
      setError(getErrorMessage(err));
    } finally {
      setLoading(false);
    }
  };

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!auth) {
      setError("Firebase não configurado corretamente.");
      return;
    }

    if (!email || !password) {
      setError("Preencha todos os campos.");
      return;
    }

    setLoading(true);
    setError('');

    try {
      if (isRegistering) {
        if (!username) {
          setError("Nome de usuário é obrigatório.");
          setLoading(false);
          return;
        }

        if (password !== confirmPassword) {
          setError("As senhas não coincidem.");
          setLoading(false);
          return;
        }

        const userCredential = await firebaseAuth.createUserWithEmailAndPassword(auth, email, password);
        await firebaseAuth.updateProfile(userCredential.user, { displayName: username });

        // Email Verification
        await firebaseAuth.sendEmailVerification(userCredential.user);
        addToast("Conta criada com sucesso! Verifique seu email.", 'success');

        await handleAuthSuccess(userCredential.user, username);
      } else {
        const userCredential = await firebaseAuth.signInWithEmailAndPassword(auth, email, password);
        await handleAuthSuccess(userCredential.user);
        addToast("Login realizado com sucesso!", 'success');
      }
    } catch (err: any) {
      const msg = getErrorMessage(err);
      setError(msg);
      addToast(msg, 'error');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="min-h-screen bg-slate-50 dark:bg-slate-900 flex items-center justify-center p-2 sm:p-4 transition-colors">
      <div className="bg-white dark:bg-slate-800 p-4 sm:p-6 rounded-2xl shadow-2xl w-full max-w-md border border-slate-200 dark:border-slate-700 max-h-screen overflow-y-auto transition-colors">

        {/* Header */}
        <div className="flex justify-center mb-3">
          <div className="w-12 h-12 bg-indigo-600 rounded-xl flex items-center justify-center shadow-lg shadow-indigo-900/50">
            <Users size={24} className="text-white" />
          </div>
        </div>

        <h1 className="text-2xl font-bold text-center text-slate-900 dark:text-white mb-1 transition-colors">PartnerSync</h1>
        <p className="text-center text-slate-600 dark:text-slate-400 text-sm mb-4 transition-colors">
          {isRegistering ? 'Crie sua conta para começar' : 'Entre para acessar seus projetos'}
        </p>

        {/* Tabs */}
        <div className="flex bg-slate-100 dark:bg-slate-900 p-1 rounded-lg mb-4 transition-colors">
          <button
            onClick={() => { setIsRegistering(false); setError(''); }}
            className={`flex-1 py-1.5 rounded-md text-sm font-medium transition-colors ${!isRegistering ? 'bg-indigo-600 text-white shadow' : 'text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-white'}`}
          >
            Entrar
          </button>
          <button
            onClick={() => { setIsRegistering(true); setError(''); }}
            className={`flex-1 py-1.5 rounded-md text-sm font-medium transition-colors ${isRegistering ? 'bg-indigo-600 text-white shadow' : 'text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-white'}`}
          >
            Cadastrar
          </button>
        </div>

        <form onSubmit={handleSubmit} className="space-y-3">

          {isRegistering && (
            <>
              <div className="relative">
                <UserIcon size={16} className="absolute left-3 top-2.5 text-slate-400 dark:text-slate-500" />
                <input
                  type="text"
                  value={username}
                  onChange={(e) => setUsername(e.target.value)}
                  className="w-full bg-slate-50 dark:bg-slate-900 border border-slate-300 dark:border-slate-600 rounded-lg pl-9 pr-3 py-2 text-sm text-slate-900 dark:text-white placeholder-slate-400 dark:placeholder-slate-500 focus:outline-none focus:ring-2 focus:ring-indigo-500 transition-all"
                  placeholder="Nome de Usuário"
                  required={isRegistering}
                />
              </div>
              <div className="relative">
                <Phone size={16} className="absolute left-3 top-2.5 text-slate-400 dark:text-slate-500" />
                <input
                  type="tel"
                  value={phone}
                  onChange={(e) => setPhone(e.target.value)}
                  className="w-full bg-slate-50 dark:bg-slate-900 border border-slate-300 dark:border-slate-600 rounded-lg pl-9 pr-3 py-2 text-sm text-slate-900 dark:text-white placeholder-slate-400 dark:placeholder-slate-500 focus:outline-none focus:ring-2 focus:ring-indigo-500 transition-all"
                  placeholder="Telefone / WhatsApp"
                  required={isRegistering}
                />
              </div>
            </>
          )}

          <div className="relative">
            <Mail size={16} className="absolute left-3 top-2.5 text-slate-400 dark:text-slate-500" />
            <input
              type="email"
              value={email}
              onChange={(e) => setEmail(e.target.value)}
              className="w-full bg-slate-50 dark:bg-slate-900 border border-slate-300 dark:border-slate-600 rounded-lg pl-9 pr-3 py-2 text-sm text-slate-900 dark:text-white placeholder-slate-400 dark:placeholder-slate-500 focus:outline-none focus:ring-2 focus:ring-indigo-500 transition-all"
              placeholder="Email"
              required
            />
          </div>

          <div className="flex items-center space-x-2 bg-slate-50 dark:bg-slate-900 border border-slate-300 dark:border-slate-600 rounded-lg px-3 py-2 transition-colors relative">
            <Lock size={16} className="text-slate-400 dark:text-slate-500" />
            <input
              type={showPassword ? "text" : "password"}
              placeholder="Senha"
              value={password}
              onChange={(e) => setPassword(e.target.value)}
              className="bg-transparent text-sm text-slate-900 dark:text-white placeholder-slate-400 dark:placeholder-slate-500 focus:outline-none flex-1"
              required
            />
            <button
              type="button"
              onClick={() => setShowPassword(!showPassword)}
              className="text-slate-400 hover:text-slate-600 dark:hover:text-slate-300 focus:outline-none"
            >
              {showPassword ? <EyeOff size={16} /> : <Eye size={16} />}
            </button>
          </div>

          {isRegistering && (
            <div className="flex items-center space-x-2 bg-slate-50 dark:bg-slate-900 border border-slate-300 dark:border-slate-600 rounded-lg px-3 py-2 transition-colors relative">
              <Lock size={16} className="text-slate-400 dark:text-slate-500" />
              <input
                type={showConfirmPassword ? "text" : "password"}
                placeholder="Confirmar Senha"
                value={confirmPassword}
                onChange={(e) => setConfirmPassword(e.target.value)}
                className="bg-transparent text-sm text-slate-900 dark:text-white placeholder-slate-400 dark:placeholder-slate-500 focus:outline-none flex-1"
                required={isRegistering}
              />
              <button
                type="button"
                onClick={() => setShowConfirmPassword(!showConfirmPassword)}
                className="text-slate-400 hover:text-slate-600 dark:hover:text-slate-300 focus:outline-none"
              >
                {showConfirmPassword ? <EyeOff size={16} /> : <Eye size={16} />}
              </button>
            </div>
          )}

          {/* Create vs Join Toggle (Only for Registration) */}
          {isRegistering && (
            <div className="p-3 border border-slate-200 dark:border-slate-700 rounded-lg bg-slate-50 dark:bg-slate-800/50 transition-colors">
              <div className="flex items-center justify-between mb-2">
                <span className="text-slate-700 dark:text-slate-300 text-sm font-medium transition-colors">Possui um código de convite?</span>
                <button
                  type="button"
                  onClick={() => { setIsJoining(!isJoining); setInviteCode(''); }}
                  className={`relative inline-flex h-5 w-9 items-center rounded-full transition-colors ${isJoining ? 'bg-indigo-600' : 'bg-slate-600'}`}
                >
                  <span className={`inline-block h-3 w-3 transform rounded-full bg-white transition duration-200 ease-in-out ${isJoining ? 'translate-x-5' : 'translate-x-1'}`} />
                </button>
              </div>

              {isJoining && (
                <div className="animate-fade-in mt-2">
                  <div className="flex items-center space-x-2 bg-slate-50 dark:bg-slate-900 border border-indigo-400 dark:border-indigo-500/50 rounded-lg p-3 transition-colors">
                    <Copy size={18} className="text-indigo-400" />
                    <input
                      type="text"
                      placeholder="Código da Empresa (ex: A1B2C3)"
                      value={inviteCode}
                      onChange={(e) => setInviteCode(e.target.value.toUpperCase())}
                      className="bg-transparent text-slate-900 dark:text-white placeholder-slate-400 dark:placeholder-slate-500 focus:outline-none flex-1 uppercase tracking-wider font-mono"
                      maxLength={6}
                    />
                  </div>
                  <p className="text-xs text-slate-500 dark:text-slate-400 mt-1 transition-colors">Peça o código ao administrador da empresa.</p>
                </div>
              )}
            </div>
          )}

          {error && (
            <div className="p-4 bg-red-500/10 border border-red-500/50 rounded-lg animate-fade-in flex flex-col space-y-2">
              <div className="flex items-start space-x-3">
                <AlertTriangle className="text-red-400 flex-shrink-0 mt-0.5" size={18} />
                <span className="text-red-400 text-sm font-medium text-left break-all">{error}</span>
              </div>
              {error.includes('DOMÍNIO BLOQUEADO') && (
                <div className="ml-7 mt-2">
                  <p className="text-xs text-slate-500 dark:text-slate-400 mb-2 transition-colors">
                    Copie o endereço acima e adicione em:<br />
                    <span className="font-mono bg-slate-100 dark:bg-slate-900 px-1 rounded transition-colors">Firebase Console &gt; Authentication &gt; Settings &gt; Authorized Domains</span>
                  </p>
                </div>
              )}
              {error.includes('ERRO DE PERMISSÃO') && (
                <div className="ml-7 mt-2">
                  <p className="text-xs text-slate-500 dark:text-slate-400 mb-2 transition-colors">
                    Vá no <strong>Firebase Console &gt; Firestore Database &gt; Rules</strong> e altere para:
                  </p>
                  <pre className="bg-slate-100 dark:bg-slate-900 p-2 rounded text-[10px] text-slate-700 dark:text-slate-300 overflow-x-auto select-all transition-colors">
                    {`rules_version = '2';
service cloud.firestore {
  match /databases/{database}/documents {
    match /{document=**} {
      allow read, write: if request.auth != null;
    }
  }
}`}
                  </pre>
                </div>
              )}
            </div>
          )}

          <button
            type="submit"
            disabled={loading}
            className="w-full bg-indigo-600 text-white font-bold py-2.5 px-4 rounded-lg hover:bg-indigo-500 transition-all transform hover:scale-[1.02] flex items-center justify-center group disabled:opacity-50 disabled:cursor-not-allowed text-sm"
          >
            {loading ? (
              <span className="animate-pulse">Processando...</span>
            ) : (
              <>
                <span>{isRegistering ? 'Criar Conta' : 'Acessar Sistema'}</span>
                <ArrowRight className="ml-2 group-hover:translate-x-1 transition-transform" size={18} />
              </>
            )}
          </button>

          <div className="relative flex py-1 items-center">
            <div className="flex-grow border-t border-slate-200 dark:border-slate-700 transition-colors"></div>
            <span className="flex-shrink-0 mx-3 text-slate-400 dark:text-slate-500 text-xs transition-colors">OU</span>
            <div className="flex-grow border-t border-slate-200 dark:border-slate-700 transition-colors"></div>
          </div>

          <button
            type="button"
            onClick={handleGoogleLogin}
            disabled={loading}
            className="w-full bg-white text-slate-900 font-bold py-2.5 px-4 rounded-lg hover:bg-slate-200 transition-all flex items-center justify-center disabled:opacity-50 text-sm"
          >
            <Chrome className="mr-2 text-red-500" size={18} />
            Entrar com Google
          </button>
        </form>

        <p className="mt-3 text-center text-xs text-slate-500 dark:text-slate-500 transition-colors">
          Sistema online sincronizado via Firebase.
        </p>
      </div>
    </div>
  );
};

export default Auth;