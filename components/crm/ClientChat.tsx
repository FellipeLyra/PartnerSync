import React, { useState, useEffect, useRef } from 'react';
import { Client, ClientMessage, User } from '../../types'; // Added User
import { crmService } from '../../services/crmService';
import { fileService } from '../../services/fileService';
import { Send, Phone, Paperclip, MoreVertical, X, Check, CheckCheck, FileText, Image as ImageIcon, Loader } from 'lucide-react';

interface ClientChatProps {
    client: Client;
    currentUser: User; // Added Prop
    companyId: string;
    onClose: () => void;
}

const ClientChat: React.FC<ClientChatProps> = ({ client, currentUser, companyId, onClose }) => {
    const [messages, setMessages] = useState<ClientMessage[]>([]);
    const [newMessage, setNewMessage] = useState('');
    const [isUploading, setIsUploading] = useState(false);
    const scrollRef = useRef<HTMLDivElement>(null);
    const fileInputRef = useRef<HTMLInputElement>(null);

    useEffect(() => {
        const unsubscribe = crmService.subscribeMessages(companyId, client.id, (data) => {
            setMessages(data);
        });
        return () => unsubscribe();
    }, [companyId, client.id]);

    useEffect(() => {
        if (scrollRef.current) {
            scrollRef.current.scrollTop = scrollRef.current.scrollHeight;
        }
    }, [messages]);

    const handleSendMessage = async (e?: React.FormEvent) => {
        e?.preventDefault();
        if (!newMessage.trim()) return;

        const message: ClientMessage = {
            id: '', // Generated by firestore
            companyId,
            clientId: client.id,
            direction: 'OUTBOUND',
            content: newMessage,
            timestamp: Date.now(),
            status: 'SENT',
            type: 'TEXT',
            senderId: currentUser.id, // Track sender
            senderName: currentUser.username // Track sender name
        };

        try {
            await crmService.sendMessage(message);
            setNewMessage('');
        } catch (error) {
            console.error("Failed to send message", error);
        }
    };

    const processFile = async (file: File) => {
        setIsUploading(true);

        try {
            // Upload to Firebase
            const path = `chat-media/${companyId}/${client.id}/${Date.now()}_${file.name}`;
            const url = await fileService.uploadFile(file, path);

            const type = file.type.startsWith('image/') ? 'IMAGE' : 'DOCUMENT';

            const message: ClientMessage = {
                id: '',
                companyId,
                clientId: client.id,
                direction: 'OUTBOUND',
                content: type === 'IMAGE' ? '📷 Imagem' : `📎 ${file.name}`,
                timestamp: Date.now(),
                status: 'SENT',
                type: type,
                mediaUrl: url,
                senderId: currentUser.id,
                senderName: currentUser.username
            };

            await crmService.sendMessage(message);
        } catch (error) {
            console.error("Upload failed", error);
            alert("Erro ao enviar arquivo. Verifique se o Storage está habilitado.");
        } finally {
            setIsUploading(false);
            if (fileInputRef.current) fileInputRef.current.value = '';
        }
    };

    const handleFileSelect = async (e: React.ChangeEvent<HTMLInputElement>) => {
        if (e.target.files && e.target.files[0]) {
            processFile(e.target.files[0]);
        }
    };

    const handlePaste = (e: React.ClipboardEvent) => {
        if (e.clipboardData.files && e.clipboardData.files.length > 0) {
            e.preventDefault(); // Prevent pasting filename text if any
            const file = e.clipboardData.files[0];
            processFile(file);
        }
    };

    // DEBUG ONLY: Simulate receiving a message
    const simulateReply = async () => {
        const message: ClientMessage = {
            id: '',
            companyId,
            clientId: client.id,
            direction: 'INBOUND',
            content: "Olá! Recebi sua mensagem. Como podemos prosseguir?",
            timestamp: Date.now(),
            status: 'READ', // Income messages don't have this status usually but for consistency
            type: 'TEXT'
        };
        await crmService.sendMessage(message);
    };

    return (
        <div className="fixed inset-0 bg-black/50 flex items-center justify-center z-50 p-4 backdrop-blur-sm">
            <div className="bg-slate-900 w-full max-w-4xl h-[85vh] rounded-2xl shadow-2xl flex overflow-hidden border border-slate-700 animate-fade-in-up">

                {/* Chat Area */}
                <div className="flex-1 flex flex-col bg-[#0b141a] relative"> {/* WhatsApp Dark Theme Background Color */}

                    {/* Header */}
                    <div className="bg-slate-800 p-4 flex justify-between items-center border-b border-slate-700">
                        <div className="flex items-center space-x-4">
                            <div className="w-10 h-10 rounded-full bg-indigo-600 flex items-center justify-center text-white font-bold text-lg">
                                {client.name.charAt(0)}
                            </div>
                            <div>
                                <h3 className="text-white font-bold">{client.name}</h3>
                                <p className="text-xs text-slate-400 flex items-center">
                                    {client.phone ? (
                                        <>
                                            <Phone size={12} className="mr-1" /> {client.phone}
                                        </>
                                    ) : 'Sem telefone cadastrado'}
                                </p>
                            </div>
                        </div>
                        <div className="flex items-center space-x-2">
                            {/* Simulation Button for Demo - REMOVED since we are clarifying use case */}
                            {client.phone && (
                                <button
                                    onClick={() => {
                                        // Sanitize phone (remove non-digits)
                                        const raw = client.phone?.replace(/\D/g, '') || '';
                                        // Basic check: if it starts with 55 (brazil) great, if not assume local and add 55 (simple heuristic for MVP)
                                        const phone = raw.length <= 11 ? `55${raw}` : raw;
                                        window.open(`https://wa.me/${phone}`, '_blank');
                                    }}
                                    className="flex items-center px-3 py-1 bg-emerald-600 hover:bg-emerald-500 text-white text-xs rounded transition-colors mr-2 font-bold"
                                    title="Abrir conversa no WhatsApp Web"
                                >
                                    <Phone size={14} className="mr-1" />
                                    Abrir WhatsApp
                                </button>
                            )}
                            <button onClick={onClose} className="p-2 hover:bg-slate-700 rounded-full text-slate-400 hover:text-white transition-colors">
                                <X size={20} />
                            </button>
                        </div>
                    </div>

                    {/* Messages */}
                    <div
                        className="flex-1 overflow-y-auto p-6 space-y-4 custom-scrollbar"
                        ref={scrollRef}
                        style={{
                            backgroundImage: "url('https://user-images.githubusercontent.com/15075759/28719144-86dc0f70-73b1-11e7-911d-60d70fcded21.png')", // Subtle whatsapp pattern
                            backgroundOpacity: 0.05,
                            backgroundBlendMode: 'overlay'
                        }}
                    >
                        {messages.length === 0 && (
                            <div className="text-center text-slate-500 mt-10 p-4 bg-slate-800/50 rounded-lg max-w-sm mx-auto">
                                <p className="text-sm">Nenhuma mensagem trocada ainda.</p>
                                <p className="text-xs mt-2">Envie a primeira mensagem para iniciar a conversa.</p>
                            </div>
                        )}

                        {messages.map((msg) => {
                            const isMe = msg.direction === 'OUTBOUND';
                            return (
                                <div key={msg.id} className={`flex ${isMe ? 'justify-end' : 'justify-start'}`}>
                                    <div
                                        className={`max-w-[70%] p-3 rounded-lg shadow-sm relative ${isMe
                                            ? 'bg-emerald-700 text-white rounded-tr-none'
                                            : 'bg-slate-800 text-slate-200 rounded-tl-none'
                                            }`}
                                    >
                                        {/* Sender Name (for shared accounts) */}
                                        {isMe && msg.senderName && msg.senderName !== currentUser.username && (
                                            <div className="text-[10px] text-emerald-200 font-bold mb-1 opacity-80">
                                                ~ {msg.senderName}
                                            </div>
                                        )}
                                        {/* Show 'You' explicitly if needed, or just hide name for self */}

                                        {msg.type === 'IMAGE' && msg.mediaUrl && (
                                            <a href={msg.mediaUrl} target="_blank" rel="noopener noreferrer">
                                                <img src={msg.mediaUrl} alt="Attachment" className="max-w-xs rounded-lg mb-2 border border-slate-600 hover:opacity-90 transition-opacity" />
                                            </a>
                                        )}
                                        {msg.type === 'DOCUMENT' && msg.mediaUrl && (
                                            <a href={msg.mediaUrl} target="_blank" rel="noopener noreferrer" className="flex items-center p-3 bg-black/20 rounded-lg mb-2 text-indigo-300 hover:text-white border border-white/10 transition-colors">
                                                <div className="bg-slate-700 p-2 rounded mr-3">
                                                    <FileText size={20} />
                                                </div>
                                                <div className="overflow-hidden">
                                                    <span className="block text-sm font-bold truncate">Arquivo Anexo</span>
                                                    <span className="text-xs opacity-70">Clique para baixar</span>
                                                </div>
                                            </a>
                                        )}

                                        <p className="text-sm whitespace-pre-wrap">{msg.content}</p>
                                        <div className="flex justify-end items-center mt-1 space-x-1">
                                            <span className="text-[10px] text-white/60">
                                                {new Date(msg.timestamp).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}
                                            </span>
                                            {isMe && (
                                                <span className="text-emerald-200">
                                                    {msg.status === 'READ' ? <CheckCheck size={14} /> : <Check size={14} />}
                                                </span>
                                            )}
                                        </div>
                                    </div>
                                </div>
                            );
                        })}
                    </div>

                    {/* Input */}
                    <div className="p-4 bg-slate-800 border-t border-slate-700">
                        <form onSubmit={handleSendMessage} className="flex items-center space-x-3">
                            <input
                                type="file"
                                ref={fileInputRef}
                                className="hidden"
                                onChange={handleFileSelect}
                            />
                            <button
                                type="button"
                                onClick={() => fileInputRef.current?.click()}
                                disabled={isUploading}
                                className={`p-2 transition-colors ${isUploading ? 'text-indigo-500 animate-pulse' : 'text-slate-400 hover:text-white'}`}
                                title="Anexar arquivo"
                            >
                                {isUploading ? <Loader size={20} className="animate-spin" /> : <Paperclip size={20} />}
                            </button>
                            {/* Quick Action: Open WhatsApp */}
                            {client.phone && (
                                <button
                                    type="button"
                                    onClick={() => {
                                        const raw = client.phone?.replace(/\D/g, '') || '';
                                        const phone = raw.length <= 11 ? `55${raw}` : raw;
                                        window.open(`https://wa.me/${phone}`, '_blank');
                                    }}
                                    className="p-2 text-emerald-500 hover:text-emerald-400 transition-colors"
                                    title="Abrir WhatsApp Web"
                                >
                                    <Phone size={20} />
                                </button>
                            )}
                            <input
                                type="text"
                                placeholder="Digite uma mensagem... (ou cole uma imagem)"
                                value={newMessage}
                                onChange={(e) => setNewMessage(e.target.value)}
                                onPaste={handlePaste}
                                className="flex-1 bg-slate-900 border border-slate-700 rounded-lg px-4 py-3 text-white outline-none focus:border-emerald-600 focus:ring-1 focus:ring-emerald-600 transition-all placeholder:text-slate-600"
                            />
                            {newMessage.trim() ? (
                                <button
                                    type="submit"
                                    className="p-3 bg-emerald-600 hover:bg-emerald-500 text-white rounded-full shadow-lg transition-transform hover:scale-105 active:scale-95"
                                >
                                    <Send size={20} />
                                </button>
                            ) : (
                                <button
                                    type="button"
                                    className="p-3 bg-slate-700 text-slate-500 rounded-full cursor-not-allowed"
                                >
                                    <Send size={20} />
                                </button>
                            )}
                        </form>
                    </div>
                </div>

                {/* Info Sidebar (Optional, hidden on small screens) */}
                <div className="w-80 bg-slate-800 border-l border-slate-700 hidden lg:flex flex-col p-6">
                    <div className="text-center mb-6">
                        <div className="w-24 h-24 rounded-full bg-slate-700 mx-auto flex items-center justify-center text-3xl font-bold text-slate-500 mb-4">
                            {client.name.charAt(0)}
                        </div>
                        <h2 className="text-xl font-bold text-white">{client.name}</h2>
                        <p className="text-slate-400 text-sm">{client.organizationName}</p>
                    </div>

                    <div className="space-y-6">
                        <div>
                            <h4 className="text-xs font-bold text-slate-500 uppercase mb-2">Detalhes do Contato</h4>
                            <div className="space-y-3">
                                <div className="flex items-center text-sm text-slate-300">
                                    <Mail className="mr-3 text-indigo-400" size={16} />
                                    {client.email || 'N/A'}
                                </div>
                                <div className="flex items-center text-sm text-slate-300">
                                    <Phone className="mr-3 text-indigo-400" size={16} />
                                    {client.phone || 'N/A'}
                                </div>
                            </div>
                        </div>

                        <div className="p-4 bg-yellow-500/10 border border-yellow-500/20 rounded-xl">
                            <h4 className="text-yellow-500 font-bold text-sm mb-2">Integração WhatsApp</h4>
                            <p className="text-xs text-yellow-200/80 leading-relaxed">
                                Esta é uma interface de demonstração.
                                Para conectar ao WhatsApp real:
                                <br />1. Configure a conta Meta Business.
                                <br />2. Conecte o webhook ao backend.
                            </p>
                        </div>
                    </div>
                </div>
            </div>
        </div>
    );
};

// Start Helper Import Fix
import { Mail } from 'lucide-react';

export default ClientChat;
